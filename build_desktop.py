"""Reproducible Windows desktop packaging; run after npm run build."""

import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parent
subprocess.run(
    [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--onedir",
        "--name",
        "Orbit",
        "--distpath",
        str(root / "dist-desktop"),
        "--workpath",
        str(root / "build-desktop"),
        "--specpath",
        str(root / "build-desktop"),
        "--add-data",
        str(root / "orbit/static") + ";orbit/static",
        "--add-data",
        str(root / "results") + ";results",
        "--collect-all",
        "webview",
        "--collect-all",
        "h5py",
        "--collect-submodules",
        "sklearn",
        "--hidden-import",
        "scipy.special._cdflib",
        "--hidden-import",
        "zeroconf",
        "--exclude-module",
        "pytest",
        "--exclude-module",
        "matplotlib",
        "--exclude-module",
        "PyQt5",
        "--exclude-module",
        "PyQt6",
        "--exclude-module",
        "IPython",
        "--exclude-module",
        "torch",
        "--exclude-module",
        "tensorflow",
        "--exclude-module",
        "jax",
        "--exclude-module",
        "pandas",
        "--exclude-module",
        "dask",
        "--exclude-module",
        "cv2",
        "--exclude-module",
        "bokeh",
        "--exclude-module",
        "plotly",
        str(root / "desktop.py"),
    ],
    check=True,
    cwd=root,
)
print("Windows desktop build complete:", root / "dist-desktop/Orbit/Orbit.exe")
